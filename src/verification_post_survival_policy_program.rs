//! Transcribed GF3258 post-survival flag-veto program for vendor raw `0x663f0`.
//!
//! Source vendor SHA-256:
//! `0a6809303f42952cd6c1915795e58cef0afacacf5204133346bd255e5188829e`.
//! Program manifest SHA-256:
//! `9bae25afb270abdbf9a741ecea10600b03c60a1fd9cd17496658f561c0d05a62`.
//!
//! This module transcribes the call-free GF3258 (`type == 0x18`) integer CFG
//! at raw `0x6640e..0x67616`. The prologue projection is represented by the
//! typed Rust inputs in `verification.rs`; this program performs only
//! the vendor's finite integer policy and its two possible flag-clear effects.

use super::{
    Gf3258PostSurvivalPolicyContext, Gf3258PostSurvivalPolicyFlags, Gf3258PostSurvivalPolicyRecord,
};

const REGISTER_COUNT: usize = 15;

const OP_NOP: i32 = 0;
const OP_MOVE: i32 = 1;
const OP_ADD: i32 = 2;
const OP_AND: i32 = 3;
const OP_IMUL: i32 = 4;
const OP_SHIFT_RIGHT_ARITHMETIC: i32 = 5;
const OP_COMPARE: i32 = 6;
const OP_TEST: i32 = 7;
const OP_SET: i32 = 8;
const OP_BRANCH: i32 = 9;
const OP_JUMP: i32 = 10;
const OP_CLEAR_SCORE_GATE: i32 = 11;
const OP_CLEAR_POLICY_CLASS: i32 = 12;
const OP_LEA_ADD: i32 = 13;
const OP_LEA_SUB_IMMEDIATE: i32 = 14;
const OP_RETURN: i32 = 15;

const IMMEDIATE_OPERAND: i32 = -1;
const STACK_MINUS_8_OPERAND: i32 = 0x101;
const STACK_MINUS_C_OPERAND: i32 = 0x102;
const STACK_MINUS_1_OPERAND: i32 = 0x201;
const TYPE_OPERAND: i32 = 0x103;
const SCORE_GATE_OPERAND: i32 = 0x300;

const CONDITION_EQUAL: i32 = 0;
const CONDITION_NOT_EQUAL: i32 = 1;
const CONDITION_GREATER: i32 = 2;
const CONDITION_GREATER_OR_EQUAL: i32 = 3;
const CONDITION_LESS: i32 = 4;
const CONDITION_LESS_OR_EQUAL: i32 = 5;
const CONDITION_SIGN: i32 = 6;
const CONDITION_NOT_SIGN: i32 = 7;
const CONDITION_ABOVE: i32 = 8;

#[derive(Debug, Clone, Copy, Default)]
struct PolicyFlags {
    zero: bool,
    sign: bool,
    overflow: bool,
    carry: bool,
}

struct PolicyVm {
    registers: [u32; REGISTER_COUNT],
    record: [u32; 15],
    stack_minus_8: u32,
    stack_minus_c: u32,
    stack_minus_1: u8,
    score_gate: u32,
    policy_class: u32,
    flags: PolicyFlags,
}

impl PolicyVm {
    fn new(
        record: Gf3258PostSurvivalPolicyRecord,
        context: Gf3258PostSurvivalPolicyContext,
        flags: Gf3258PostSurvivalPolicyFlags,
    ) -> Self {
        let record = [
            i32_bits(record.geometry_count_00),
            i32_bits(record.metric_04),
            i32_bits(record.field_10),
            i32_bits(record.field_14),
            i32_bits(record.field_1c),
            i32_bits(record.field_20),
            i32_bits(record.field_24),
            i32_bits(record.field_28),
            i32_bits(record.field_2c),
            i32_bits(record.field_30),
            i32_bits(record.field_34),
            i32_bits(record.field_38),
            i32_bits(record.live_scalar_54),
            i32_bits(record.enrolled_scalar_5c),
            i32_bits(record.field_64),
        ];
        let mut registers = [0; REGISTER_COUNT];

        // Exact live 32-bit state at raw 0x6640e after the six-register
        // prologue. Stack locals -8/-c are populated by program rows 1/5.
        registers[0] = record[7]; // EAX = work +0x28
        registers[1] = record[12].wrapping_add(record[13]); // EBX = +0x54 + +0x5c
        registers[2] = i32_bits(context.candidate_state); // ECX
        registers[3] = i32_bits(context.scalar_56); // EDX
        registers[4] = i32_bits(context.scalar_43); // ESI
        registers[6] = record[8]; // EBP = work +0x2c
        registers[7] = i32_bits(context.mode_value); // R8D
        registers[8] = i32_bits(context.ratio_q8); // R9D
        registers[9] = record[0]; // R10D = work +0x00
        registers[10] = record[3]; // R11D = work +0x14
        registers[11] = record[5]; // R12D = work +0x20
        registers[14] = record[1]; // R15D = work +0x04

        Self {
            registers,
            record,
            stack_minus_8: 0,
            stack_minus_c: 0,
            stack_minus_1: 0,
            score_gate: i32_bits(flags.score_gate),
            policy_class: i32_bits(flags.policy_class),
            flags: PolicyFlags::default(),
        }
    }

    fn operand_is_byte(operand: i32) -> bool {
        (16..=30).contains(&operand) || operand == STACK_MINUS_1_OPERAND
    }

    fn read_operand(&self, operand: i32, immediate: i32) -> u32 {
        match operand {
            IMMEDIATE_OPERAND => i32_bits(immediate),
            0..=14 => self.registers[to_usize(operand)],
            16..=30 => self.registers[to_usize(operand - 16)] & 0xff,
            32..=46 => self.record[to_usize(operand - 32)],
            STACK_MINUS_8_OPERAND => self.stack_minus_8,
            STACK_MINUS_C_OPERAND => self.stack_minus_c,
            STACK_MINUS_1_OPERAND => self.stack_minus_1.into(),
            TYPE_OPERAND => 0x18,
            SCORE_GATE_OPERAND => self.score_gate,
            _ => unreachable!("invalid post-survival operand"),
        }
    }

    fn write_operand(&mut self, operand: i32, value: u32) {
        match operand {
            0..=14 => self.registers[to_usize(operand)] = value,
            16..=30 => {
                let index = to_usize(operand - 16);
                self.registers[index] = (self.registers[index] & 0xffff_ff00) | (value & 0xff);
            }
            STACK_MINUS_8_OPERAND => self.stack_minus_8 = value,
            STACK_MINUS_C_OPERAND => self.stack_minus_c = value,
            STACK_MINUS_1_OPERAND => self.stack_minus_1 = value.to_le_bytes()[0],
            _ => unreachable!("invalid post-survival destination"),
        }
    }

    fn set_subtraction_flags(&mut self, lhs: u32, rhs: u32, width_is_byte: bool) {
        if width_is_byte {
            let lhs = lhs.to_le_bytes()[0];
            let rhs = rhs.to_le_bytes()[0];
            let result = lhs.wrapping_sub(rhs);
            self.flags.zero = result == 0;
            self.flags.sign = result & 0x80 != 0;
            self.flags.carry = lhs < rhs;
            self.flags.overflow = ((lhs ^ rhs) & (lhs ^ result) & 0x80) != 0;
        } else {
            let result = lhs.wrapping_sub(rhs);
            self.flags.zero = result == 0;
            self.flags.sign = result & 0x8000_0000 != 0;
            self.flags.carry = lhs < rhs;
            self.flags.overflow = ((lhs ^ rhs) & (lhs ^ result) & 0x8000_0000) != 0;
        }
    }

    fn set_logic_flags(&mut self, value: u32, width_is_byte: bool) {
        if width_is_byte {
            let value = value.to_le_bytes()[0];
            self.flags.zero = value == 0;
            self.flags.sign = value & 0x80 != 0;
        } else {
            self.flags.zero = value == 0;
            self.flags.sign = value & 0x8000_0000 != 0;
        }
        self.flags.overflow = false;
        self.flags.carry = false;
    }

    fn condition(&self, condition: i32) -> bool {
        match condition {
            CONDITION_EQUAL => self.flags.zero,
            CONDITION_NOT_EQUAL => !self.flags.zero,
            CONDITION_GREATER => !self.flags.zero && self.flags.sign == self.flags.overflow,
            CONDITION_GREATER_OR_EQUAL => self.flags.sign == self.flags.overflow,
            CONDITION_LESS => self.flags.sign != self.flags.overflow,
            CONDITION_LESS_OR_EQUAL => self.flags.zero || self.flags.sign != self.flags.overflow,
            CONDITION_SIGN => self.flags.sign,
            CONDITION_NOT_SIGN => !self.flags.sign,
            CONDITION_ABOVE => !self.flags.carry && !self.flags.zero,
            _ => unreachable!("invalid post-survival condition"),
        }
    }

    fn run(mut self) -> Gf3258PostSurvivalPolicyFlags {
        let mut pc = 0usize;
        loop {
            let [opcode, a, b, c] = PROGRAM[pc];
            let mut next = pc + 1;
            match opcode {
                OP_NOP => {}
                OP_MOVE => {
                    let value = self.read_operand(b, c);
                    self.write_operand(a, value);
                }
                OP_ADD => {
                    let lhs = self.read_operand(a, 0);
                    let rhs = self.read_operand(b, c);
                    let value = lhs.wrapping_add(rhs);
                    self.write_operand(a, value);
                    // No reachable conditional branch consumes this ADD's flags
                    // before a later CMP/TEST. Preserve only value semantics.
                }
                OP_AND => {
                    let width_is_byte = Self::operand_is_byte(a) || Self::operand_is_byte(b);
                    let mut value = self.read_operand(a, 0) & self.read_operand(b, c);
                    if width_is_byte {
                        value &= 0xff;
                    }
                    self.write_operand(a, value);
                    self.set_logic_flags(value, width_is_byte);
                }
                OP_IMUL => {
                    let lhs = bits_i32(self.read_operand(a, 0));
                    let rhs = bits_i32(self.read_operand(b, c));
                    self.write_operand(a, i32_bits(lhs.wrapping_mul(rhs)));
                    // Flags are overwritten before any reachable consumer.
                }
                OP_SHIFT_RIGHT_ARITHMETIC => {
                    let value = bits_i32(self.read_operand(a, 0));
                    let shift = self.read_operand(b, c) & 31;
                    self.write_operand(a, i32_bits(value >> shift));
                    // Flags are overwritten before any reachable consumer.
                }
                OP_COMPARE => {
                    let width_is_byte = Self::operand_is_byte(a) || Self::operand_is_byte(b);
                    self.set_subtraction_flags(
                        self.read_operand(a, 0),
                        self.read_operand(b, c),
                        width_is_byte,
                    );
                }
                OP_TEST => {
                    let width_is_byte = Self::operand_is_byte(a) || Self::operand_is_byte(b);
                    let mut value = self.read_operand(a, 0) & self.read_operand(b, c);
                    if width_is_byte {
                        value &= 0xff;
                    }
                    self.set_logic_flags(value, width_is_byte);
                }
                OP_SET => self.write_operand(a, if self.condition(c) { 1 } else { 0 }),
                OP_BRANCH => {
                    if self.condition(c) {
                        next = to_usize(a);
                    }
                }
                OP_JUMP => next = to_usize(a),
                OP_CLEAR_SCORE_GATE => self.score_gate = 0,
                OP_CLEAR_POLICY_CLASS => self.policy_class = 0,
                OP_LEA_ADD => {
                    let value = self
                        .read_operand(b, 0)
                        .wrapping_add(self.read_operand(c, 0));
                    self.write_operand(a, value);
                }
                OP_LEA_SUB_IMMEDIATE => {
                    let value = self.read_operand(b, 0).wrapping_sub(i32_bits(c));
                    self.write_operand(a, value);
                }
                OP_RETURN => {
                    return Gf3258PostSurvivalPolicyFlags {
                        score_gate: bits_i32(self.score_gate),
                        policy_class: bits_i32(self.policy_class),
                    };
                }
                _ => unreachable!("invalid post-survival opcode"),
            }
            pc = next;
        }
    }
}

