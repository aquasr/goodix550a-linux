//! Transcribed GF3258 pre-tail policy program for vendor raw `0x69740`.
//!
//! Source vendor SHA-256:
//! `0a6809303f42952cd6c1915795e58cef0afacacf5204133346bd255e5188829e`.
//! Program manifest SHA-256:
//! `1473fd5f00478acec121016e863cbc916677461f61294cd3ab3d50fb4453f148`.
//!
//! The GF3258 (`type == 0x18`) body is call-free. This module models only its
//! finite integer CFG. The seven-row prefix preserves the recovered vendor
//! program layout: execution starts at program index 7, raw address `0x698c8`.

use super::{Gf3258PreTailPolicyContext, Gf3258PreTailPolicyRecord};

const PROGRAM_ENTRY: usize = 7;
const REGISTER_COUNT: usize = 16;
const MEMORY_SIZE: usize = 0x1400;
const WORK_BASE: u64 = 0x0100;
const AGREEMENT_BASE: u64 = 0x0400;
const STACK_BASE: u64 = 0x0c00;

const KIND_REGISTER: i64 = 0;
const KIND_IMMEDIATE: i64 = 1;
const KIND_MEMORY: i64 = 2;
const KIND_ADDRESS: i64 = 3;

const OP_NOP: usize = 0;
const OP_MOV: usize = 1;
const OP_MOVSXD: usize = 2;
const OP_LEA: usize = 3;
const OP_CMP: usize = 4;
const OP_TEST: usize = 5;
const OP_ADD: usize = 6;
const OP_SUB: usize = 7;
const OP_AND: usize = 8;
const OP_OR: usize = 9;
const OP_XOR: usize = 10;
const OP_SHL: usize = 11;
const OP_SAR: usize = 12;
const OP_NEG: usize = 13;
const OP_IMUL: usize = 14;
const OP_CDQ: usize = 15;
const OP_IDIV: usize = 16;
const OP_JMP: usize = 17;
const OP_RET: usize = 18;
const OP_SET_BASE: usize = 32;
const OP_CMOV_BASE: usize = 48;
const OP_JCC_BASE: usize = 64;

#[derive(Debug, Clone, Copy, Default)]
struct Flags {
    zero: bool,
    sign: bool,
    overflow: bool,
    carry: bool,
}

struct Vm {
    registers: [u64; REGISTER_COUNT],
    memory: [u8; MEMORY_SIZE],
    flags: Flags,
}

impl Vm {
    fn new(record: Gf3258PreTailPolicyRecord, context: Gf3258PreTailPolicyContext) -> Self {
        let mut vm = Self {
            registers: [0; REGISTER_COUNT],
            memory: [0; MEMORY_SIZE],
            flags: Flags::default(),
        };

        // Canonical register order is RAX, RCX, RDX, RBX, RSP, RBP, RSI, RDI,
        // R8..R15, matching the transcribed operand table.
        vm.registers[4] = STACK_BASE;
        vm.registers[6] = WORK_BASE;
        vm.registers[8] = i32_bits(context.mapped_mode);
        vm.registers[9] = i32_bits(context.profile_mode);
        vm.registers[10] = 1; // type == 0x18 dispatch state
        vm.registers[11] = 0;
        vm.registers[14] = AGREEMENT_BASE;

        let fields = [
            (0x00, record.geometry_count),
            (0x04, record.verification_metric),
            (0x10, record.map_score),
            (0x14, record.evidence),
            (0x20, record.field_20),
            (0x24, record.scaled_coverage_q8),
            (0x28, record.matched_percent),
            (0x2c, record.geometry_percent),
            (0x34, record.orthogonality_penalty),
            (0x38, record.severe_orthogonality),
            (0x54, record.live_quality),
            (0x5c, record.enrolled_quality),
        ];
        for (offset, value) in fields {
            vm.write_memory(WORK_BASE + offset, 32, i32_bits(value));
        }
        // After the vendor prologue, raw argument seven is at RSP+0x38.
        vm.write_memory(STACK_BASE + 0x38, 32, i32_bits(context.auxiliary_mode));
        vm.write_memory(
            AGREEMENT_BASE + 0x04,
            32,
            i32_bits(context.agreement.both_zero),
        );
        vm.write_memory(AGREEMENT_BASE + 0x08, 32, i32_bits(context.agreement.mixed));
        vm.write_memory(
            AGREEMENT_BASE + 0x0c,
            32,
            i32_bits(context.agreement.both_one),
        );
        vm
    }

    fn address(&self, operand: usize) -> u64 {
        let [
            _kind,
            _width,
            _register,
            base,
            index,
            scale,
            displacement,
            _immediate,
        ] = OPERANDS[operand];
        let mut address = i128::from(displacement);
        if base >= 0 {
            address += i128::from(self.registers[to_usize_i64(base)]);
        }
        if index >= 0 {
            address += i128::from(self.registers[to_usize_i64(index)]) * i128::from(scale);
        }
        address as u64
    }

    fn read_memory(&self, address: u64, width: u32) -> u64 {
        let bytes = (width / 8) as usize;
        let start = usize::try_from(address).expect("pre-tail address fits usize");
        let end = start.checked_add(bytes).expect("pre-tail memory range");
        assert!(end <= MEMORY_SIZE, "pre-tail read outside virtual memory");
        let mut value = 0u64;
        for index in 0..bytes {
            value |= u64::from(self.memory[start + index]) << (index * 8);
        }
        value
    }

    fn write_memory(&mut self, address: u64, width: u32, value: u64) {
        let bytes = (width / 8) as usize;
        let start = usize::try_from(address).expect("pre-tail address fits usize");
        let end = start.checked_add(bytes).expect("pre-tail memory range");
        assert!(end <= MEMORY_SIZE, "pre-tail write outside virtual memory");
        for index in 0..bytes {
            self.memory[start + index] = (value >> (index * 8)) as u8;
        }
    }

    fn read_operand(&self, operand: usize) -> (u64, u32) {
        let [
            kind,
            width,
            register,
            _base,
            _index,
            _scale,
            _displacement,
            immediate,
        ] = OPERANDS[operand];
        match kind {
            KIND_REGISTER => {
                let width = u32::try_from(width).expect("pre-tail register width");
                (self.registers[to_usize_i64(register)] & mask(width), width)
            }
            KIND_IMMEDIATE => (immediate as u64, 0),
            KIND_MEMORY => {
                let width = u32::try_from(width).expect("pre-tail memory width");
                (self.read_memory(self.address(operand), width), width)
            }
            KIND_ADDRESS => (self.address(operand), 64),
            _ => unreachable!("invalid pre-tail operand kind"),
        }
    }

    fn write_operand(&mut self, operand: usize, value: u64) {
        let [
            kind,
            width,
            register,
            _base,
            _index,
            _scale,
            _displacement,
            _immediate,
        ] = OPERANDS[operand];
        let width = u32::try_from(width).expect("pre-tail destination width");
        match kind {
            KIND_REGISTER => {
                let index = to_usize_i64(register);
                let value = value & mask(width);
                if width == 64 || width == 32 {
                    self.registers[index] = value;
                } else {
                    self.registers[index] = (self.registers[index] & !mask(width)) | value;
                }
            }
            KIND_MEMORY => self.write_memory(self.address(operand), width, value),
            _ => unreachable!("invalid pre-tail destination"),
        }
    }

    fn logic_flags(&mut self, value: u64, width: u32) {
        let value = value & mask(width);
        self.flags.zero = value == 0;
        self.flags.sign = value & sign_bit(width) != 0;
        self.flags.overflow = false;
        self.flags.carry = false;
    }

    fn subtraction_flags(&mut self, lhs: u64, rhs: u64, width: u32) -> u64 {
        let lhs = lhs & mask(width);
        let rhs = rhs & mask(width);
        let result = lhs.wrapping_sub(rhs) & mask(width);
        self.flags.zero = result == 0;
        self.flags.sign = result & sign_bit(width) != 0;
        self.flags.carry = lhs < rhs;
        self.flags.overflow = ((lhs ^ rhs) & (lhs ^ result) & sign_bit(width)) != 0;
        result
    }

    fn addition_flags(&mut self, lhs: u64, rhs: u64, width: u32) -> u64 {
        let lhs = lhs & mask(width);
        let rhs = rhs & mask(width);
        let result = lhs.wrapping_add(rhs) & mask(width);
        self.flags.zero = result == 0;
        self.flags.sign = result & sign_bit(width) != 0;
        self.flags.carry = lhs > mask(width).wrapping_sub(rhs);
        self.flags.overflow = (!(lhs ^ rhs) & (lhs ^ result) & sign_bit(width)) != 0;
        result
    }

    fn condition(&self, condition: usize) -> bool {
        match condition {
            0 => self.flags.zero,
            1 => !self.flags.zero,
            2 => !self.flags.zero && self.flags.sign == self.flags.overflow,
            3 => self.flags.zero || self.flags.sign != self.flags.overflow,
            4 => self.flags.sign != self.flags.overflow,
            5 => self.flags.sign == self.flags.overflow,
            6 => !self.flags.carry && !self.flags.zero,
            7 => !self.flags.carry,
            8 => self.flags.carry,
            9 => self.flags.carry || self.flags.zero,
            10 => self.flags.sign,
            11 => !self.flags.sign,
            _ => unreachable!("invalid pre-tail condition"),
        }
    }

    fn run(mut self) -> i32 {
        let mut pc = PROGRAM_ENTRY;
        loop {
            let [opcode, a, b, _c] = PROGRAM[pc];
            let next = pc + 1;
            match opcode {
                OP_NOP => pc = next,
                OP_MOV => {
                    let (value, _) = self.read_operand(b);
                    self.write_operand(a, value);
                    pc = next;
                }
                OP_MOVSXD => {
                    let (value, _) = self.read_operand(b);
                    self.write_operand(
                        a,
                        u64::from_ne_bytes(i64::from(bits_i32(value as u32)).to_ne_bytes()),
                    );
                    pc = next;
                }
                OP_LEA => {
                    let (value, _) = self.read_operand(b);
                    self.write_operand(a, value);
                    pc = next;
                }
                OP_CMP => {
                    let (lhs, width) = self.read_operand(a);
                    let (rhs, _) = self.read_operand(b);
                    self.subtraction_flags(lhs, rhs, width);
                    pc = next;
                }
                OP_TEST => {
                    let (lhs, width) = self.read_operand(a);
                    let (rhs, _) = self.read_operand(b);
                    self.logic_flags(lhs & rhs, width);
                    pc = next;
                }
                OP_ADD | OP_SUB | OP_AND | OP_OR | OP_XOR => {
                    let (lhs, width) = self.read_operand(a);
                    let (rhs, _) = self.read_operand(b);
                    let value = match opcode {
                        OP_ADD => self.addition_flags(lhs, rhs, width),
                        OP_SUB => self.subtraction_flags(lhs, rhs, width),
                        OP_AND => {
                            let value = lhs & rhs;
                            self.logic_flags(value, width);
                            value
                        }
                        OP_OR => {
                            let value = lhs | rhs;
                            self.logic_flags(value, width);
                            value
                        }
                        OP_XOR => {
                            let value = lhs ^ rhs;
                            self.logic_flags(value, width);
                            value
                        }
                        _ => unreachable!(),
                    };
                    self.write_operand(a, value);
                    pc = next;
                }
                OP_SHL | OP_SAR => {
                    let (value, width) = self.read_operand(a);
                    let (count, _) = self.read_operand(b);
                    let count_mask = if width == 64 { 0x3f } else { 0x1f };
                    let count = (count & count_mask) as u32;
                    if count != 0 {
                        let shifted = if opcode == OP_SHL {
                            value.wrapping_shl(count) & mask(width)
                        } else {
                            signed(value, width).wrapping_shr(count) as u64 & mask(width)
                        };
                        self.write_operand(a, shifted);
                        self.logic_flags(shifted, width);
                    }
                    pc = next;
                }
                OP_NEG => {
                    let (value, width) = self.read_operand(a);
                    let negated = self.subtraction_flags(0, value, width);
                    self.write_operand(a, negated);
                    pc = next;
                }
                OP_IMUL => {
                    let (lhs, width) = self.read_operand(a);
                    let (rhs, _) = self.read_operand(b);
                    let value =
                        signed(lhs, width).wrapping_mul(signed(rhs, width)) as u64 & mask(width);
                    self.write_operand(a, value);
                    pc = next;
                }
                OP_CDQ => {
                    self.registers[2] = if bits_i32(self.registers[0] as u32) < 0 {
                        u64::from(u32::MAX)
                    } else {
                        0
                    };
                    pc = next;
                }
                OP_IDIV => {
                    let (divisor, width) = self.read_operand(a);
                    debug_assert_eq!(width, 32);
                    let divisor = i64::from(bits_i32(divisor as u32));
                    let dividend_bits = ((self.registers[2] & 0xffff_ffff) << 32)
                        | (self.registers[0] & 0xffff_ffff);
                    let dividend = dividend_bits as i64;
                    let quotient = dividend / divisor;
                    let remainder = dividend % divisor;
                    self.registers[0] = quotient as u32 as u64;
                    self.registers[2] = remainder as u32 as u64;
                    pc = next;
                }
                OP_JMP => pc = a,
                OP_RET => return bits_i32(self.registers[0] as u32),
                opcode if (OP_SET_BASE..OP_SET_BASE + 12).contains(&opcode) => {
                    self.write_operand(a, self.condition(opcode - OP_SET_BASE) as u64);
                    pc = next;
                }
                opcode if (OP_CMOV_BASE..OP_CMOV_BASE + 12).contains(&opcode) => {
                    if self.condition(opcode - OP_CMOV_BASE) {
                        let (value, _) = self.read_operand(b);
                        self.write_operand(a, value);
                    }
                    pc = next;
                }
                opcode if (OP_JCC_BASE..OP_JCC_BASE + 12).contains(&opcode) => {
                    pc = if self.condition(opcode - OP_JCC_BASE) {
                        a
                    } else {
                        next
                    };
                }
                _ => unreachable!("invalid pre-tail opcode"),
            }
        }
    }
}

#[inline]
pub(super) fn rejects(
    record: Gf3258PreTailPolicyRecord,
    context: Gf3258PreTailPolicyContext,
) -> bool {
    Vm::new(record, context).run() != 0
}

#[inline]
const fn i32_bits(value: i32) -> u64 {
    value as u32 as u64
}

#[inline]
const fn bits_i32(value: u32) -> i32 {
    i32::from_ne_bytes(value.to_ne_bytes())
}

#[inline]
const fn mask(width: u32) -> u64 {
    if width == 64 {
        u64::MAX
    } else {
        (1u64 << width) - 1
    }
}

#[inline]
const fn sign_bit(width: u32) -> u64 {
    1u64 << (width - 1)
}

#[inline]
fn signed(value: u64, width: u32) -> i64 {
    if width == 64 {
        value as i64
    } else {
        let value = value & mask(width);
        if value & sign_bit(width) != 0 {
            (value | !mask(width)) as i64
        } else {
            value as i64
        }
    }
}

#[inline]
fn to_usize_i64(value: i64) -> usize {
    usize::try_from(value).expect("pre-tail index is non-negative")
}

