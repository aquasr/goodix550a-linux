//! Transcribed GF3258 late-policy decision program for vendor raw `0x6bb90`.
//!
//! Source vendor SHA-256:
//! `0a6809303f42952cd6c1915795e58cef0afacacf5204133346bd255e5188829e`.
//! Program manifest SHA-256:
//! `080bba3c4699cf149d8b617506bfe3b4013757eb139f933d2a946067fa4e4bac`.
//!
//! The instruction table represents the post-overlap, call-free integer CFG at
//! `0x6bc88..0x704ef`. Do not hand-edit individual program rows. The small VM
//! below expresses only the integer operations present in that finite acyclic
//! graph; geometry remains implemented by the typed Rust registration helpers.

use super::{Gf3258LatePolicyContext, Gf3258LatePolicyOutcome, Gf3258LatePolicyRecord};

const REGISTER_COUNT: usize = 15;
const STACK_BYTES: usize = 0x40;
const PROGRAM_TERMINAL: usize = 874;

const OP_NOP: i32 = 0;
const OP_MOVE: i32 = 1;
const OP_ADD: i32 = 2;
const OP_XOR: i32 = 3;
const OP_AND: i32 = 4;
const OP_OR: i32 = 5;
const OP_IMUL: i32 = 6;
const OP_SHIFT_LEFT: i32 = 7;
const OP_COMPARE: i32 = 8;
const OP_TEST: i32 = 9;
const OP_SET: i32 = 10;
const OP_CONDITIONAL_MOVE: i32 = 11;
const OP_BRANCH: i32 = 12;
const OP_JUMP: i32 = 13;
const OP_CLEAR_PRIMARY_FLAG: i32 = 14;
const OP_IMUL_THREE_OPERAND: i32 = 100;
const OP_LEA: i32 = 101;

const IMMEDIATE_OPERAND: i32 = -1;
const REJECT_COUNT_OPERAND: i32 = 0x300;

const CONDITION_EQUAL: i32 = 0;
const CONDITION_NOT_EQUAL: i32 = 1;
const CONDITION_GREATER: i32 = 2;
const CONDITION_GREATER_OR_EQUAL: i32 = 3;
const CONDITION_LESS: i32 = 4;
const CONDITION_LESS_OR_EQUAL: i32 = 5;

#[derive(Debug, Clone, Copy, Default)]
struct PolicyFlags {
    zero: bool,
    signed_less: bool,
}

struct PolicyVm {
    registers: [u32; REGISTER_COUNT],
    stack: [u8; STACK_BYTES],
    record: [u32; 13],
    reject_count: u32,
    flags: PolicyFlags,
    clear_primary_flag: bool,
}

impl PolicyVm {
    fn new(
        record: Gf3258LatePolicyRecord,
        context: Gf3258LatePolicyContext,
        overlap_count: i32,
    ) -> Self {
        let mut vm = Self {
            registers: [0; REGISTER_COUNT],
            stack: [0; STACK_BYTES],
            record: [
                i32_bits(record.geometry_count_00),
                i32_bits(record.metric_04),
                i32_bits(record.field_10),
                i32_bits(record.field_14),
                i32_bits(record.field_20),
                i32_bits(record.field_24),
                i32_bits(record.field_28),
                i32_bits(record.field_2c),
                i32_bits(record.field_34),
                i32_bits(record.field_38),
                i32_bits(record.live_scalar_54),
                i32_bits(record.enrolled_scalar_5c),
                i32_bits(record.field_64),
            ],
            reject_count: i32_bits(context.current_reject_count),
            flags: PolicyFlags::default(),
            clear_primary_flag: false,
        };

        // Exact live state at raw 0x6bc88, immediately after the two overlap
        // calls and their max reduction. EAX's second-overlap value is dead on
        // every path before use, so only the max in R15D is semantically needed.
        vm.registers[1] = 80 * 64; // EBX
        vm.registers[11] = 0x18; // R12D: GF3258 type
        vm.registers[12] = 64; // R13D
        vm.registers[13] = 80; // R14D
        vm.registers[14] = i32_bits(overlap_count); // R15D
        vm.registers[3] = vm.record[3]; // EDX = work +0x14
        vm.registers[2] = vm.record[4]; // ECX = work +0x20

        vm.write_stack_u32(0x08, i32_bits(context.history_high));
        vm.write_stack_u32(0x0c, i32_bits(context.live_quality));
        vm.write_stack_u32(0x10, i32_bits(context.profile_max()));
        vm.write_stack_u32(0x14, vm.record[11]);
        vm.write_stack_u32(
            0x38,
            i32_bits(record.enrolled_scalar_5c.wrapping_add(context.live_quality)),
        );
        vm
    }

    fn read_stack_u32(&self, offset: usize) -> u32 {
        u32::from_le_bytes([
            self.stack[offset],
            self.stack[offset + 1],
            self.stack[offset + 2],
            self.stack[offset + 3],
        ])
    }

    fn write_stack_u32(&mut self, offset: usize, value: u32) {
        let bytes = value.to_le_bytes();
        self.stack[offset] = bytes[0];
        self.stack[offset + 1] = bytes[1];
        self.stack[offset + 2] = bytes[2];
        self.stack[offset + 3] = bytes[3];
    }

    fn operand_width(operand: i32) -> u8 {
        if (16..=30).contains(&operand) || (0x200..=0x23f).contains(&operand) {
            8
        } else {
            32
        }
    }

    fn read_operand(&self, operand: i32, immediate: i32) -> u32 {
        match operand {
            IMMEDIATE_OPERAND => i32_bits(immediate),
            0..=14 => self.registers[to_usize(operand)],
            16..=30 => self.registers[to_usize(operand - 16)] & 0xff,
            32..=44 => self.record[to_usize(operand - 32)],
            0x100..=0x13f => self.read_stack_u32(to_usize(operand - 0x100)),
            0x200..=0x23f => self.stack[to_usize(operand - 0x200)].into(),
            REJECT_COUNT_OPERAND => self.reject_count,
            _ => unreachable!("invalid late-policy operand"),
        }
    }

    fn write_operand(&mut self, operand: i32, value: u32) {
        match operand {
            0..=14 => self.registers[to_usize(operand)] = value,
            16..=30 => {
                let index = to_usize(operand - 16);
                self.registers[index] = (self.registers[index] & 0xffff_ff00) | (value & 0xff);
            }
            0x100..=0x13f => self.write_stack_u32(to_usize(operand - 0x100), value),
            0x200..=0x23f => self.stack[to_usize(operand - 0x200)] = value.to_le_bytes()[0],
            _ => unreachable!("invalid late-policy destination"),
        }
    }

    fn set_comparison_flags(&mut self, lhs: u32, rhs: u32, width: u8) {
        if width == 8 {
            let lhs = i8::from_ne_bytes([lhs.to_le_bytes()[0]]);
            let rhs = i8::from_ne_bytes([rhs.to_le_bytes()[0]]);
            self.flags.zero = lhs == rhs;
            self.flags.signed_less = lhs < rhs;
        } else {
            let lhs = bits_i32(lhs);
            let rhs = bits_i32(rhs);
            self.flags.zero = lhs == rhs;
            self.flags.signed_less = lhs < rhs;
        }
    }

    fn set_logic_flags(&mut self, value: u32, width: u8) {
        if width == 8 {
            let value = value.to_le_bytes()[0];
            self.flags.zero = value == 0;
            self.flags.signed_less = value & 0x80 != 0;
        } else {
            self.flags.zero = value == 0;
            self.flags.signed_less = value & 0x8000_0000 != 0;
        }
    }

    fn condition(&self, condition: i32) -> bool {
        match condition {
            CONDITION_EQUAL => self.flags.zero,
            CONDITION_NOT_EQUAL => !self.flags.zero,
            CONDITION_GREATER => !self.flags.zero && !self.flags.signed_less,
            CONDITION_GREATER_OR_EQUAL => !self.flags.signed_less,
            CONDITION_LESS => self.flags.signed_less,
            CONDITION_LESS_OR_EQUAL => self.flags.zero || self.flags.signed_less,
            _ => unreachable!("invalid late-policy condition"),
        }
    }

    fn run(mut self) -> Gf3258LatePolicyOutcome {
        let mut pc = 0usize;
        while pc != PROGRAM_TERMINAL {
            let [opcode, a, b, c] = PROGRAM[pc];
            let next = pc + 1;
            match opcode {
                OP_NOP => {}
                OP_MOVE => {
                    let value = self.read_operand(b, c);
                    self.write_operand(a, value);
                }
                OP_ADD => {
                    let value = self
                        .read_operand(a, 0)
                        .wrapping_add(self.read_operand(b, c));
                    self.write_operand(a, value);
                }
                OP_XOR => {
                    let value = self.read_operand(a, 0) ^ self.read_operand(b, c);
                    self.write_operand(a, value);
                    self.set_logic_flags(value, Self::operand_width(a));
                }
                OP_AND => {
                    let value = self.read_operand(a, 0) & self.read_operand(b, c);
                    self.write_operand(a, value);
                    self.set_logic_flags(value, Self::operand_width(a));
                }
                OP_OR => {
                    let value = self.read_operand(a, 0) | self.read_operand(b, c);
                    self.write_operand(a, value);
                    self.set_logic_flags(value, Self::operand_width(a));
                }
                OP_IMUL => {
                    let value = self
                        .read_operand(a, 0)
                        .wrapping_mul(self.read_operand(b, c));
                    self.write_operand(a, value);
                }
                OP_SHIFT_LEFT => {
                    let shift = self.read_operand(b, c) & 31;
                    let value = self.read_operand(a, 0).wrapping_shl(shift);
                    self.write_operand(a, value);
                }
                OP_COMPARE => {
                    let width = Self::operand_width(a);
                    self.set_comparison_flags(
                        self.read_operand(a, 0),
                        self.read_operand(b, c),
                        width,
                    );
                }
                OP_TEST => {
                    let width = Self::operand_width(a);
                    let value = self.read_operand(a, 0) & self.read_operand(b, c);
                    self.set_logic_flags(value, width);
                }
                OP_SET => {
                    let value = if self.condition(c) { 1 } else { 0 };
                    self.write_operand(a, value);
                }
                OP_CONDITIONAL_MOVE => {
                    if self.condition(c) {
                        let value = self.read_operand(b, 0);
                        self.write_operand(a, value);
                    }
                }
                OP_BRANCH => {
                    if self.condition(c) {
                        pc = to_usize(a);
                        continue;
                    }
                }
                OP_JUMP => {
                    pc = to_usize(a);
                    continue;
                }
                OP_CLEAR_PRIMARY_FLAG => self.clear_primary_flag = true,
                OP_IMUL_THREE_OPERAND => {
                    let value = bits_i32(self.read_operand(b, 0)).wrapping_mul(c);
                    self.write_operand(a, i32_bits(value));
                }
                OP_LEA => {
                    let index_operand = (c >> 8) & 0xff;
                    let scale = i32_bits(c & 0xff);
                    let indexed = if index_operand == 0xff {
                        0
                    } else {
                        self.read_operand(index_operand, 0).wrapping_mul(scale)
                    };
                    let value = self.read_operand(b, 0).wrapping_add(indexed);
                    self.write_operand(a, value);
                }
                _ => unreachable!("invalid late-policy opcode"),
            }
            pc = next;
        }

        Gf3258LatePolicyOutcome {
            reject: self.registers[0] == 1,
            clear_primary_flag: self.clear_primary_flag,
        }
    }
}

#[inline]
const fn i32_bits(value: i32) -> u32 {
    u32::from_ne_bytes(value.to_ne_bytes())
}

#[inline]
const fn bits_i32(value: u32) -> i32 {
    i32::from_ne_bytes(value.to_ne_bytes())
}

#[inline]
fn to_usize(value: i32) -> usize {
    usize::try_from(value).expect("late-policy index must be nonnegative")
}

pub(super) fn classify(
    record: Gf3258LatePolicyRecord,
    context: Gf3258LatePolicyContext,
    overlap_count: i32,
) -> Gf3258LatePolicyOutcome {
    PolicyVm::new(record, context, overlap_count).run()
}

